"use client";

import { useActionState } from "react";
import {
  startTotpEnrollment,
  verifyTotpCode,
  type EnrollmentState,
  type VerifyState,
} from "./actions";

function CodeForm({ factorId, next, label }: { factorId: string; next: string; label: string }) {
  const [state, action, pending] = useActionState<VerifyState, FormData>(verifyTotpCode, {});
  return (
    <form action={action} style={{ marginTop: "1.5rem", display: "grid", gap: "0.75rem" }}>
      <input type="hidden" name="factorId" value={factorId} />
      <input type="hidden" name="next" value={next} />
      <label htmlFor="totp-code">{label}</label>
      <input
        id="totp-code"
        name="code"
        inputMode="numeric"
        autoComplete="one-time-code"
        pattern="\s*\d{3}\s*\d{3}\s*"
        maxLength={7}
        required
        autoFocus
      />
      {state.error && (
        <p role="alert" style={{ color: "#b42318" }}>
          {state.error}
        </p>
      )}
      <button type="submit" disabled={pending}>
        {pending ? "Checking…" : "Verify"}
      </button>
    </form>
  );
}

// Returning staff: enter the current code to unlock the staff area.
export function VerifyCodeForm({ factorId, next }: { factorId: string; next: string }) {
  return (
    <CodeForm factorId={factorId} next={next} label="6-digit code from your authenticator app" />
  );
}

// First time: set up an authenticator app, then confirm it with a code.
export function EnrollTotp({ next }: { next: string }) {
  const [state, start, pending] = useActionState<EnrollmentState>(startTotpEnrollment, {
    status: "idle",
  });

  if (state.status !== "enrolling") {
    return (
      <form action={start} style={{ marginTop: "1.5rem" }}>
        {state.status === "error" && (
          <p role="alert" style={{ color: "#b42318", marginBottom: "0.75rem" }}>
            {state.message}
          </p>
        )}
        <button type="submit" disabled={pending}>
          {pending ? "Preparing…" : "Set up authenticator app"}
        </button>
      </form>
    );
  }

  return (
    <div style={{ marginTop: "1.5rem" }}>
      <p>
        Scan this QR code with an authenticator app (for example Google Authenticator, Microsoft
        Authenticator or 1Password).
      </p>
      {/* The QR code is an inline SVG data URI generated by Supabase; next/image adds nothing here. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img
        src={state.qrCode}
        alt="QR code for your authenticator app"
        width={200}
        height={200}
        style={{ marginTop: "1rem", background: "#fff", padding: "0.5rem" }}
      />
      <p style={{ marginTop: "1rem" }}>
        Can&apos;t scan it? Enter this key manually: <code>{state.secret}</code>
      </p>
      <CodeForm
        factorId={state.factorId}
        next={next}
        label="Then enter the 6-digit code it shows"
      />
    </div>
  );
}
